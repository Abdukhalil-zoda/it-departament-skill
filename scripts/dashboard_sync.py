    def link(self, full, title=None, table=False):
        """Link to an existing file: wikilink when it is inside the vault and its name resolves, otherwise a
        markdown link relative to the dashboard (files outside the vault, hidden folders, unlinkable names)."""
        name = os.path.basename(full.rstrip('/\\'))
        target = name[:-3] if name.lower().endswith('.md') else name
        if inside(full, self.vault) and self.resolves(target):
            return wikilink(target, title, table)
        return '[%s](%s)' % (md_text(title or name, table), md_url(fwd(full, self.vault)))

    def doc(self, path, title=None, table=False, where=''):
        """(link text, exists) for a project-relative document path or URL; missing paths are warned."""
        path = path.strip()
        if re.match(r'^[A-Za-z][A-Za-z0-9+.-]*://', path):
            return '[%s](%s)' % (md_text(title or path, table), path), True
        full = path if os.path.isabs(path) else os.path.join(self.root, path)
        if not os.path.exists(full):
            self.warn('missing document: %s%s' % (path, (' (%s)' % where) if where else ''))
            return '%s (missing)' % code(path, table), False
        return self.link(full, title, table), True

    def note_link(self, n, alias=None):
        alias = alias or n['id']
        return self.link(n['path'], alias if alias != n['stem'] else None, table=True)

    def task_links(self, value, where):
        """Ids found in a parent_task / linked_task value -> wikilinks, or 'ID (missing)' when no note has that name."""
        text = text_of(value)
        ids, out = [], []
        for i in re.findall(r'\b[A-Z][A-Z0-9]*-\d+\b', text):
            if i not in ids:
                ids.append(i)
        for i in ids:
            if self.resolves(i):
                out.append('[[%s]]' % i)
            else:
                self.warn('unresolved link: %s (%s)' % (i, where))
                out.append('%s (missing)' % i)
        return ', '.join(out) if out else esc(text)

    def delink(self, text, where):
        """Safety net for VL006: a wikilink that does not resolve in the vault (e.g. typed into a title) is turned
        into its plain text; links inside code spans are left alone, as the lint ignores them."""
        def fix(m):
            target = link_target(m.group(1))
            if not target or self.resolves(target):
                return m.group(0)
            self.warn('unresolved wikilink [[%s]] shown as text (%s block)' % (m.group(1).replace('\\|', '|'), where))
            return link_label(m.group(1))
        out, pos = [], 0
        for m in INLINE_CODE_RE.finditer(text):
            out.append(WIKILINK_RE.sub(fix, text[pos:m.start()]) + m.group(0))
            pos = m.end()
        return ''.join(out) + WIKILINK_RE.sub(fix, text[pos:])

