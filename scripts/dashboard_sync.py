# --------------------------------------------------------------------------- merging blocks into the file
def marker(name, which):
    return '<!-- sync:%s %s -->' % (name, which)


def find_block(text, name):
    """(start, end) offsets of the text between the markers, None when absent, 'broken' when unbalanced."""
    starts = list(re.finditer(r'<!--\s*sync:%s\s+start\s*-->' % re.escape(name), text))
    ends = list(re.finditer(r'<!--\s*sync:%s\s+end\s*-->' % re.escape(name), text))
    if not starts and not ends:
        return None
    if len(starts) != 1 or len(ends) != 1 or ends[0].start() < starts[0].end():
        return 'broken'
    return starts[0].end(), ends[0].start()


def heading_index(lines, pattern):
    """First '## ' heading (outside code fences) matching the pattern and not already followed by a block."""
    rx, fence = re.compile(pattern, re.I), False
    for i, line in enumerate(lines):
        if line.lstrip().startswith(('```', '~~~')):
            fence = not fence
            continue
        if fence or not re.match(r'^##[ \t]', line) or not rx.search(line[2:]):
            continue
        j = i + 1
        while j < len(lines) and not lines[j].strip():
            j += 1
        if j < len(lines) and ANY_START_RE.search(lines[j]):
            continue
        return i
    return None


def tip_index(lines):
    for i in range(len(lines) - 1, -1, -1):
        nxt = lines[i + 1] if i + 1 < len(lines) else ''
        if re.match(r'^\s*>\s*\[!TIP\]', lines[i], re.I) and 'obsidian' in (lines[i] + nxt).lower():
            return i
    return None


def insert_block(text, name, content, journal=True):
    """Insert a block into a dashboard that has no markers for it (a new section keeps its static lines only
    when journal is true, i.e. when [[decisions-log]] resolves in the vault)."""
    _name, heading, pattern, extra = SECTION[name]
    extra = extra if journal else ()
    block = [marker(name, 'start')] + content.split('\n') + [marker(name, 'end')]
    lines = text.split('\n')
    if name == 'header':
        idx = next((i for i, line in enumerate(lines) if line.startswith('# ')), None)
    else:
        idx = heading_index(lines, pattern)
    if idx is None and name == 'header':
        return '\n'.join(block + [''] + lines)
    if idx is not None:
        after = lines[idx + 1:]
        return '\n'.join(lines[:idx + 1] + [''] + block + ([''] if after and after[0].strip() else []) + after)
    section = [heading, ''] + block + list(extra)
    tip = tip_index(lines)
    if tip is not None:
        before = lines[:tip]
        if before and before[-1].strip():
            before.append('')
        return '\n'.join(before + section + ['', '---', ''] + lines[tip:])
    body = list(lines)
    while body and not body[-1].strip():
        body.pop()
    if body and body[-1].strip() != '---':
        body += ['', '---']
    return '\n'.join(body + [''] + section) + '\n'


def merge(text, blocks, journal=True):
    """-> (new text, inserted block names, block names with broken markers)."""
    inserted, broken = [], []
    for name in BLOCKS:
        span = find_block(text, name)
        if span is None:
            text = insert_block(text, name, blocks[name], journal)
            inserted.append(name)
        elif span == 'broken':
            broken.append(name)
        else:
            text = text[:span[0]] + '\n' + blocks[name] + '\n' + text[span[1]:]
    return text, inserted, broken


def last_updated_of(text):
    span = find_block(text, 'header')
    if not isinstance(span, tuple):
        return None
    m = re.search(r'^\*\*Last Updated:\*\*[ \t]*(.*?)[ \t]*$', text[span[0]:span[1]], re.M)
    return m.group(1) if m and m.group(1) else None


def skeleton(journal=True):
    """Dashboard layout with empty marker pairs (used when the vault template cannot be found)."""
    lines = [TITLE, '', NOTE, '', marker('header', 'start'), marker('header', 'end'), '', '---', '']
    for name, heading, _pattern, extra in SECTIONS[1:]:
        lines += [heading, '', marker(name, 'start'), marker(name, 'end')] + list(extra if journal else ()) + ['', '---', '']
    return '\n'.join(lines + list(TIP)) + '\n'


def template_text(journal=True):
    """Base text of a new dashboard: the vault template (its static decisions-journal line dropped when the
    journal does not resolve), or the built-in skeleton when the template is not reachable."""
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'assets', 'vault-template', DASHBOARD)
    try:
        text = read_text(path)
    except OSError:
        return skeleton(journal)
    return text if journal else text.replace('\n\n' + JOURNAL_LINE + '\n', '\n')


