def read_text(path):
    """UTF-8 text with the BOM dropped and line endings normalised to LF."""
    with open(path, 'rb') as fh:
        text = fh.read().decode('utf-8', errors='replace')
    if text.startswith('\N{ZERO WIDTH NO-BREAK SPACE}'):
        text = text[1:]
    return text.replace('\r\n', '\n').replace('\r', '\n')


def write_text(path, text):
    """Atomic write (temp file + rename) as UTF-8 with LF endings, keeping the file mode."""
    folder = os.path.dirname(path) or '.'
    fd, tmp = tempfile.mkstemp(prefix='.dashboard-', suffix='.tmp', dir=folder)
    try:
        with os.fdopen(fd, 'w', encoding='utf-8', newline='\n') as fh:
            fh.write(text)
        if os.path.exists(path):
            os.chmod(tmp, stat.S_IMODE(os.stat(path).st_mode))
        else:
            mask = os.umask(0)
            os.umask(mask)
            os.chmod(tmp, 0o666 & ~mask)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.remove(tmp)
        except OSError:
            pass
        raise


def walk_md(top):
    out = []
    if not os.path.isdir(top):
        return out
    for dp, dn, fn in os.walk(top):
        dn[:] = sorted(d for d in dn if not d.startswith('.'))
        out += [os.path.join(dp, f) for f in sorted(fn) if f.lower().endswith('.md') and not f.startswith('.')]
    return out


def fwd(path, base):
    """Path relative to base with forward slashes (absolute when on another drive)."""
    try:
        r = os.path.relpath(path, base)
    except ValueError:
        r = os.path.abspath(path)
    return r.replace(os.sep, '/')


def inside(path, folder):
    try:
        f = os.path.normcase(os.path.abspath(folder))
        return os.path.commonpath([os.path.normcase(os.path.abspath(path)), f]) == f
    except ValueError:
        return False


def id_key(value):
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r'(\d+)', str(value))]


def canon(value, choices):
    s = str(value if value is not None else '').strip().lower()
    return next((c for c in choices if c.lower() == s), None)


def text_of(value):
    if value is None:
        return ''
    if isinstance(value, list):
        return ', '.join(text_of(x) for x in value)
    if isinstance(value, bool):
        return 'true' if value else 'false'
    return str(value).replace('\n', ' ').strip()


def esc(value):
    """Table cell text: '|' escaped, empty -> em dash."""
    s = text_of(value)
    return s.replace('|', '\\|') if s else DASH


def code(value, table=True):
    s = text_of(value).replace('`', "'")
    if not s:
        return DASH
    return '`%s`' % (s.replace('|', '\\|') if table else s)


def md_text(text, table=False):
    s = str(text).replace('\\', '\\\\').replace('[', '\\[').replace(']', '\\]')
    return s.replace('|', '\\|') if table else s


def md_url(path):
    return ''.join(URL_ESCAPES.get(c, c) for c in path)


def wikilink(target, alias=None, table=False):
    if alias and alias != target:
        alias = str(alias).replace('|', '/').replace('[', '(').replace(']', ')')
        return '[[%s%s%s]]' % (target, '\\|' if table else '|', alias)
    return '[[%s]]' % target


def link_target(inner):
    """'Target#heading|alias' (or the table-escaped 'Target\\|alias') -> 'Target'."""
    target = inner.split('|', 1)[0].rstrip()
    if target.endswith('\\'):
        target = target[:-1]
    return target.split('#', 1)[0].strip()


def link_label(inner):
    """Visible text of a wikilink: its alias, else its target."""
    return inner.split('|', 1)[1].strip() if '|' in inner else link_target(inner)


def fmt(n):
    return '{:,}'.format(int(n)).replace(',', ' ')


def is_num(v):
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def number(v):
    return fmt(v) if is_num(v) else 'n/a'


def delta_str(prev, cur):
    if not is_num(prev) or not is_num(cur):
        return 'n/a'
    if prev == 0:
        return '+inf' if cur else '0%'
    return '%+.0f%%' % ((cur - prev) / prev * 100)


def parse_ts(value):
    """Aware datetime from an ISO timestamp ('Z' allowed; naive = UTC), or None."""
    if not isinstance(value, str) or not value.strip():
        return None
    s = value.strip()
    if s[-1:] in ('Z', 'z'):
        s = s[:-1] + '+00:00'
    try:
        dt = datetime.datetime.fromisoformat(s)
    except ValueError:
        return None
    return dt if dt.tzinfo else dt.replace(tzinfo=datetime.timezone.utc)


def parse_date(value):
    try:
        return datetime.date.fromisoformat(str(value)[:10])
    except ValueError:
        return None


def date_in(name):
    m = re.search(r'(\d{4}-\d{2}-\d{2})', name)
    return m.group(1) if m else ''


