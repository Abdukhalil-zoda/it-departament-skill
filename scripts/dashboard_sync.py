def sync(root, check=False, quiet=False, out=None):
    """Regenerate (or with check=True only compare) the dashboard of the project at root; returns the exit code."""
    out = out or sys.stdout

    def say(msg):
        print(msg, file=out)
    root = os.path.abspath(root)
    d = Dashboard(root, load_config(root), _now())
    if not os.path.isdir(d.vault):
        print('dashboard_sync: vault not found: %s (check --root and paths.vault_relative_path)' % d.vault, file=sys.stderr)
        return 2
    d.scan()
    body = d.render_body()
    exists = os.path.isfile(d.path)
    current = read_text(d.path) if exists else ''
    base = current if exists else template_text(d.journal)
    old = last_updated_of(base)
    changed = True
    if exists and old:
        new, inserted, broken = merge(base, dict(body, header=d.r_header(old)), d.journal)
        changed = new != current
    if changed:
        new, inserted, broken = merge(base, dict(body, header=d.r_header(d.now.strftime('%Y-%m-%d %H:%M'))), d.journal)
    for name in broken:
        d.warn('block %s has unbalanced or duplicate sync markers - left unchanged' % name)
    stats = '(%d tasks, %d bugs, %d warnings)' % (len(d.tasks), len(d.bugs), len(d.warnings))
    if not quiet:
        if not exists:
            say('%s %s from the vault template' % ('would create' if check else 'creating', d.rel(d.path)))
        for name in inserted if exists else []:
            say('%s block %s' % ('would insert' if check else 'inserted', name))
        for w in d.warnings:
            say('warning: ' + w)
    if check:
        if changed and not quiet:
            diff = list(difflib.unified_diff(current.split('\n'), new.split('\n'), 'a/' + d.rel(d.path),
                                             'b/' + d.rel(d.path), lineterm=''))
            for line in diff[:DIFF_LIMIT]:
                say(line)
            if len(diff) > DIFF_LIMIT:
                say('... (%d more diff lines)' % (len(diff) - DIFF_LIMIT))
        say(d.path)
        say('dashboard: %s %s' % ('out of date' if changed else 'up to date', stats))
        return 1 if changed or broken else 0
    if changed:
        write_text(d.path, new)
    say(d.path)
    say('dashboard: %s %s' % ('updated' if changed else 'unchanged', stats))
    return 1 if broken else 0


def main(argv=None):
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(errors='replace')
        except Exception:
            pass
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--root', default=os.getcwd(), help='project root (holds .it-department/config.json)')
    ap.add_argument('--check', action='store_true', help='compare only; exit 1 when the dashboard is out of date')
    ap.add_argument('--quiet', action='store_true', help='print only the dashboard path and the summary line')
    a = ap.parse_args(argv)
    return sync(a.root, check=a.check, quiet=a.quiet)


if __name__ == '__main__':
    sys.exit(main())
