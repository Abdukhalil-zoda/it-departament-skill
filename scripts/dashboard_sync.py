INT_RE = re.compile(r'^[-+]?(?:0|[1-9][0-9]*)$')


def comment_start(raw):
    """Index of a YAML comment (' #' outside quotes) in a value, or -1."""
    quote, i, n = None, 0, len(raw)
    while i < n:
        ch = raw[i]
        if quote:
            if quote == '"' and ch == '\\':
                i += 2
                continue
            if ch == quote:
                if quote == "'" and i + 1 < n and raw[i + 1] == "'":
                    i += 2
                    continue
                quote = None
        elif ch in '"\'':
            before = raw[:i].rstrip()
            if not before or before[-1] in '[{,:':
                quote = ch
        elif ch == '#' and (i == 0 or raw[i - 1] in ' \t'):
            return i
        i += 1
    return -1


def strip_comment(raw):
    i = comment_start(raw)
    return (raw if i < 0 else raw[:i]).strip()


def split_items(inner):
    """Split the inside of an inline list or map on top-level commas (quotes and brackets respected)."""
    items, buf, depth, quote, i = [], '', 0, None, 0
    while i < len(inner):
        ch = inner[i]
        if quote:
            buf += ch
            if quote == '"' and ch == '\\' and i + 1 < len(inner):
                buf += inner[i + 1]
                i += 2
                continue
            if ch == quote:
                quote = None
        elif ch in '"\'' and (not buf.strip() or buf.rstrip().endswith(':')):
            quote = ch
            buf += ch
        elif ch in '[{':
            depth += 1
            buf += ch
        elif ch in ']}':
            depth -= 1
            buf += ch
        elif ch == ',' and depth == 0:
            items.append(buf.strip())
            buf = ''
        else:
            buf += ch
        i += 1
    items.append(buf.strip())
    return [x for x in items if x]


def unquote(v):
    if len(v) >= 2 and v[0] == v[-1] == '"':
        return re.sub(r'\\(["\\])', r'\1', v[1:-1])
    if len(v) >= 2 and v[0] == v[-1] == "'":
        return v[1:-1].replace("''", "'")
    return v


def parse_scalar(v):
    """Quoted string, true/false, null, integer, inline list [a, b]; anything else stays a raw string."""
    v = v.strip()
    if not v:
        return ''
    if len(v) >= 2 and v[0] == v[-1] and v[0] in '"\'':
        return unquote(v)
    if v in ('true', 'True', 'TRUE'):
        return True
    if v in ('false', 'False', 'FALSE'):
        return False
    if v in ('null', 'Null', 'NULL', '~'):
        return None
    if INT_RE.match(v):
        return int(v)
    if v[0] == '[' and v[-1] == ']':
        return [parse_scalar(x) for x in split_items(v[1:-1])]
    return v


def parse_frontmatter(text):
    """(dict, body) for text that starts with a '---' block, (None, text) otherwise.

    Supports `key: value` lines with quoted strings, booleans, integers, inline lists, block lists
    (`- item` lines under an empty key), one level of indented `key: value` pairs, and ` #` comments.
    """
    lines = text.split('\n')
    if not lines or lines[0].strip() != '---':
        return None, text
    end = next((i for i in range(1, len(lines)) if lines[i].rstrip() == '---'), None)
    if end is None:
        return None, text
    fm, i = {}, 1
    while i < end:
        m = KEY_RE.match(lines[i])
        i += 1
        if not m:
            continue
        key, raw = m.group(1), strip_comment(m.group(2) or '')
        if raw:
            fm[key] = parse_scalar(raw)
            continue
        items, nested = [], {}
        while i < end:
            line = lines[i]
            s = line.strip()
            if s and not s.startswith('#'):
                if s == '-' or s.startswith('- '):
                    items.append(parse_scalar(strip_comment(s[1:])))
                elif line[:1] in ' \t':
                    nm = NESTED_RE.match(s)
                    if nm:
                        nested[unquote(nm.group(1).strip())] = parse_scalar(strip_comment(nm.group(2) or ''))
                else:
                    break
            i += 1
        fm[key] = items if items else (nested if nested else '')
    return fm, '\n'.join(lines[end + 1:])


def inline_map(value):
    """{a: 1, b: 2} written inline in frontmatter (kept as a raw string by the parser) -> dict."""
    if isinstance(value, dict):
        return value
    s = value.strip() if isinstance(value, str) else ''
    if not (s.startswith('{') and s.endswith('}')):
        return {}
    out = {}
    for item in split_items(s[1:-1]):
        k, sep, v = item.partition(':')
        if sep:
            out[unquote(k.strip())] = parse_scalar(v)
    return out


def first_heading(body):
    for line in body.split('\n'):
        if line.startswith('# '):
            return line[2:].strip()
    return ''


